// The pictures on the documentation site, made by the library they advertise.
//
// A page about compression that shows no compression is asking to be taken on
// trust. So every image the site displays is produced here, by Lathe, and the
// byte counts printed beside them are the real sizes of the real files — not
// figures typed into HTML once and left to rot.
//
//     swift run --package-path Benchmarks lathe-siteassets
//
// The source image is SYNTHETIC and deliberately so. A photograph would need a
// licence and would make the repository heavier every time it changed; a
// generated scene can be regenerated by anyone who checks out the code. It is
// built out of the four things that actually make codecs struggle — a smooth
// gradient (banding), fine high-frequency texture (detail loss), hard-edged
// type (ringing), and saturated colour boundaries (chroma subsampling) — so
// the artefacts a slider is meant to reveal are the ones really there.

import CoreGraphics
import CoreText
import Foundation
import ImageIO
import LatheCore
import LatheImage
import UniformTypeIdentifiers

/// A fixed-seed generator, so running this twice produces the same picture.
///
/// The scene is randomised — the texture and the ridge — and with the system
/// generator every run wrote different bytes. The images are committed, so
/// that made regenerating the site a diff of five binary files that nobody
/// could review and nothing had actually changed in.
///
/// SplitMix64: a handful of lines, well-distributed, and — the point here —
/// specified, so the sequence is a property of the algorithm rather than of
/// the toolchain that happened to compile it.
struct Seeded: RandomNumberGenerator {
    private var state: UInt64

    init(seed: UInt64 = 0x1A7E_5EED_0000_0001) { state = seed }

    mutating func next() -> UInt64 {
        state &+= 0x9E37_79B9_7F4A_7C15
        var z = state
        z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
        z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
        return z ^ (z >> 31)
    }
}

// MARK: - Where things go

let root = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent()   // lathe-siteassets
    .deletingLastPathComponent()   // Sources
    .deletingLastPathComponent()   // Benchmarks
    .deletingLastPathComponent()   // repository root
let mediaDirectory = root.appendingPathComponent("docs/media", isDirectory: true)
try FileManager.default.createDirectory(at: mediaDirectory, withIntermediateDirectories: true)

let width = 1440
let height = 900

// MARK: - The source

/// Draws the scene. Everything here is chosen to be hard to compress in a
/// specific, visible way.
func drawSource(into context: CGContext) {
    let w = CGFloat(width), h = CGFloat(height)

    // A wide, slow gradient. The first thing to band when bit depth is spent
    // elsewhere, and the reason a "looks fine" screenshot often isn't.
    let space = CGColorSpaceCreateDeviceRGB()
    let sky = CGGradient(
        colorsSpace: space,
        colors: [
            CGColor(red: 0.05, green: 0.10, blue: 0.22, alpha: 1),
            CGColor(red: 0.42, green: 0.21, blue: 0.35, alpha: 1),
            CGColor(red: 0.95, green: 0.55, blue: 0.24, alpha: 1),
            CGColor(red: 0.99, green: 0.84, blue: 0.55, alpha: 1),
        ] as CFArray,
        locations: [0, 0.45, 0.78, 1])!
    context.drawLinearGradient(
        sky, start: CGPoint(x: 0, y: h), end: CGPoint(x: 0, y: h * 0.28),
        options: [])

    // Fine high-frequency texture. What a low bitrate smears into mush, and
    // the reason "smaller" and "the same" are different claims.
    var generator = Seeded()
    context.saveGState()
    context.clip(to: CGRect(x: 0, y: 0, width: w, height: h * 0.34))
    for _ in 0..<26_000 {
        let x = CGFloat.random(in: 0...w, using: &generator)
        let y = CGFloat.random(in: 0...(h * 0.34), using: &generator)
        let shade = CGFloat.random(in: 0.06...0.30, using: &generator)
        context.setFillColor(CGColor(red: shade, green: shade * 0.9, blue: shade * 0.8, alpha: 1))
        context.fill(CGRect(x: x, y: y, width: 1.6, height: 1.6))
    }
    context.restoreGState()

    // Hard edges against flat colour — where ringing shows up first.
    let ridge = CGMutablePath()
    ridge.move(to: CGPoint(x: 0, y: h * 0.30))
    var x: CGFloat = 0
    var peak: CGFloat = h * 0.30
    while x < w {
        let step = CGFloat.random(in: 40...120, using: &generator)
        peak = min(max(peak + CGFloat.random(in: -70...70, using: &generator), h * 0.18), h * 0.52)
        ridge.addLine(to: CGPoint(x: x + step, y: peak))
        x += step
    }
    ridge.addLine(to: CGPoint(x: w, y: 0))
    ridge.addLine(to: CGPoint(x: 0, y: 0))
    ridge.closeSubpath()
    context.setFillColor(CGColor(red: 0.08, green: 0.09, blue: 0.13, alpha: 1))
    context.addPath(ridge)
    context.fillPath()

    // Saturated patches side by side. Chroma subsampling bleeds across exactly
    // this kind of boundary, and nothing else on the page would show it.
    let swatches: [(CGFloat, CGFloat, CGFloat)] = [
        (0.85, 0.18, 0.12), (0.95, 0.62, 0.10), (0.16, 0.55, 0.42),
        (0.12, 0.35, 0.72), (0.55, 0.20, 0.60), (0.90, 0.85, 0.20),
    ]
    let swatchWidth = w / CGFloat(swatches.count)
    for (index, colour) in swatches.enumerated() {
        context.setFillColor(CGColor(red: colour.0, green: colour.1, blue: colour.2, alpha: 1))
        context.fill(CGRect(
            x: CGFloat(index) * swatchWidth, y: h * 0.055,
            width: swatchWidth, height: h * 0.075))
    }

    // Type. Small, high-contrast glyphs are the most legible evidence a reader
    // has that quality was lost, because you can read the damage.
    let text = "LATHE" as CFString
    let font = CTFontCreateWithName("Helvetica-Bold" as CFString, 168, nil)
    let attributes = [
        kCTFontAttributeName: font,
        kCTForegroundColorAttributeName: CGColor(red: 1, green: 1, blue: 1, alpha: 0.96),
    ] as CFDictionary
    let attributed = CFAttributedStringCreate(nil, text, attributes)!
    let line = CTLineCreateWithAttributedString(attributed)
    context.textPosition = CGPoint(x: 64, y: h * 0.63)
    CTLineDraw(line, context)

    let caption = "on-device media processing · no subprocesses" as CFString
    let small = CTFontCreateWithName("Menlo" as CFString, 25, nil)
    let captionAttributes = [
        kCTFontAttributeName: small,
        kCTForegroundColorAttributeName: CGColor(red: 1, green: 1, blue: 1, alpha: 0.82),
    ] as CFDictionary
    let captionLine = CTLineCreateWithAttributedString(
        CFAttributedStringCreate(nil, caption, captionAttributes)!)
    context.textPosition = CGPoint(x: 68, y: h * 0.575)
    CTLineDraw(captionLine, context)
}

guard let context = CGContext(
    data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
    space: CGColorSpaceCreateDeviceRGB(),
    bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)
else { fatalError("could not create the drawing context") }

drawSource(into: context)
guard let sourceImage = context.makeImage() else { fatalError("could not render the source") }

/// The reference. PNG because it is lossless and every browser shows it — this
/// is the "before" the slider compares against.
let originalURL = mediaDirectory.appendingPathComponent("comparison-original.png")
do {
    guard let destination = CGImageDestinationCreateWithURL(
        originalURL as CFURL, UTType.png.identifier as CFString, 1, nil)
    else { fatalError("no PNG destination") }
    CGImageDestinationAddImage(destination, sourceImage, nil)
    guard CGImageDestinationFinalize(destination) else { fatalError("PNG write failed") }
}

// MARK: - The comparisons

struct Encoded: Codable {
    let format: String
    let label: String
    let file: String
    let bytes: Int
    let quality: Double
    /// Which of the two settings this is. The site leads with the one people
    /// would actually ship.
    let tier: String
    /// Whether every browser will display it. Only Safari shows HEIC.
    let displayable: Bool
    /// For a format not every browser shows: the encoded file, decoded by
    /// ImageIO and saved losslessly. It is the HEIC's own pixels, damage and
    /// all, so a browser that cannot read the file still shows what it holds.
    /// The size on the page stays the size of the encoded file.
    let preview: String?
}

/// Decodes `url` and writes its pixels to `preview` as PNG.
func writeDecodedPreview(of url: URL, to preview: URL) {
    guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
          let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
          let destination = CGImageDestinationCreateWithURL(
              preview as CFURL, UTType.png.identifier as CFString, 1, nil)
    else { fatalError("could not decode \(url.lastPathComponent)") }
    CGImageDestinationAddImage(destination, image, nil)
    guard CGImageDestinationFinalize(destination) else { fatalError("preview write failed") }
}

/// Two settings, because they answer different questions and only showing one
/// of them misleads.
///
/// **Visually lossless** is the honest sales pitch: the setting somebody would
/// really use, where the point is that you look hard and cannot find the
/// damage — and it is still a large saving. A slider that only ever showed
/// obvious artefacts would be advertising how small a file can get while
/// quietly conceding it looks worse.
///
/// **Pushed hard** is what the same encoder does when told to stop caring. It
/// earns its place by showing where each format breaks first, which is the
/// thing a comparison is actually good for — and it is labelled, so nobody
/// mistakes it for the recommended setting.
let tiers: [(name: String, quality: Double)] = [
    ("Visually lossless", 0.80),
    ("Pushed hard", 0.32),
]

let formats: [(ImageFormat, String, String, Bool)] = [
    (.avif, "AVIF", "avif", true),
    (.webp, "WebP", "webp", true),
    (.jpeg, "JPEG", "jpg", true),
    (.heic, "HEIC", "heic", false),
]

var encoded: [Encoded] = []
let encoder = ImageEncoder()

for tier in tiers {
    for (format, label, ext, displayable) in formats {
        guard EncodeSupport.shared.canEncode(format) else {
            FileHandle.standardError.write(Data("skipped \(label): not encodable here\n".utf8))
            continue
        }
        let slug = tier.name.lowercased().replacingOccurrences(of: " ", with: "-")
        let filename = "comparison-\(ext)-\(slug).\(ext)"
        let output = mediaDirectory.appendingPathComponent(filename)
        _ = try await encoder.encode(
            source: originalURL, to: output, format: format,
            quality: .quality(tier.quality), resize: ResizeTarget.none, metadata: .stripAll)
        let bytes = (try output.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0
        var preview: String?
        if !displayable {
            let name = "comparison-\(ext)-\(slug)-decoded.png"
            writeDecodedPreview(of: output, to: mediaDirectory.appendingPathComponent(name))
            preview = name
        }
        encoded.append(Encoded(
            format: String(describing: format), label: label, file: filename,
            bytes: bytes, quality: tier.quality, tier: tier.name,
            displayable: displayable, preview: preview))
        print("\(tier.name) \(label): \(bytes) bytes")
    }
}

let originalBytes = (try originalURL.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0
print("PNG source: \(originalBytes) bytes")

struct Manifest: Codable {
    let width: Int
    let height: Int
    let originalFile: String
    let originalBytes: Int
    let tiers: [String]
    let encodings: [Encoded]
    let generatedAt: String
}

let manifest = Manifest(
    width: width, height: height,
    originalFile: originalURL.lastPathComponent, originalBytes: originalBytes,
    tiers: tiers.map(\.name), encodings: encoded,
    generatedAt: ISO8601DateFormatter().string(from: Date()))

let encoderJSON = JSONEncoder()
encoderJSON.outputFormatting = [.prettyPrinted, .sortedKeys]
try encoderJSON.encode(manifest)
    .write(to: mediaDirectory.appendingPathComponent("comparison.json"), options: .atomic)

print("wrote \(encoded.count) encodings to \(mediaDirectory.path)")
