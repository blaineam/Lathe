import Foundation
import LatheCore

// The comparison harness.
//
// ## The three claims this is built to test
//
// 1. **Comparable output.** Where Lathe and a tool use the same library, the
//    files should match. A row that shows parity is a row doing its job.
// 2. **Faster where hardware exists**, and faster on small work because there is
//    no process to launch.
// 3. **It runs where the tools cannot** — in-process, no subprocess, on iOS,
//    shippable to the App Store. That row is not measurable here and is stated
//    rather than timed.
//
// ## Rules, because a table nobody can check is worth nothing
//
// * Same input, same target quality, same output format, both sides.
// * Best of N runs, not the mean — a mean on a laptop measures what else the
//   machine was doing.
// * The tools' **process launch is counted**, because it is real and is exactly
//   what an in-process library does not pay. It is called out rather than
//   subtracted.
// * Quality is measured by ffmpeg (VMAF for video, SSIM for stills). ffmpeg is
//   the instrument in those rows, not a contestant.
// * Every version is printed with the table.
// * **Rows Lathe loses are kept.** A table where one side wins everything is not
//   believed, and would not be true.

func main() async {
    var comparisons: [Comparison] = []
    var skipped: [String] = []

    FileHandle.standardError.write(Data("building fixtures…\n".utf8))
    let still: URL
    let video: URL
    let audio: URL
    do {
        still = try Fixtures.stillPNG()
        video = try await Fixtures.video()
        audio = try Fixtures.audioWAV()
    } catch {
        FileHandle.standardError.write(Data("fixtures failed: \(error)\n".utf8))
        exit(1)
    }

    let cases: [(String, () async throws -> Comparison?)] = [
        ("WebP", { try await Cases.webP(source: still) }),
        ("JPEG", { try await Cases.jpeg(source: still) }),
        ("AVIF", { try await Cases.avif(source: still) }),
        ("HEVC vs x265", { try await Cases.hevcSoftware(source: video) }),
        ("HEVC vs VideoToolbox", { try await Cases.hevcHardware(source: video) }),
        ("AAC", { try await Cases.aac(source: audio) }),
        ("MP3", { try await Cases.mp3(source: audio) }),
        ("Probe", { try await Cases.probe(source: video) }),
        ("Metadata", { try await Cases.metadataWrite(source: still) }),
    ]

    for (name, body) in cases {
        FileHandle.standardError.write(Data("  \(name)…\n".utf8))
        do {
            if let comparison = try await body() {
                comparisons.append(comparison)
            } else {
                skipped.append("\(name) — the tool it compares against is not installed")
            }
        } catch {
            skipped.append("\(name) — \(error)")
        }
    }

    emit(comparisons, skipped: skipped)
}

func emit(_ comparisons: [Comparison], skipped: [String]) {
    print("<!-- Generated by lathe-bench. Do not edit by hand. -->")
    print("\n## Lathe against the tools\n")
    print("| task | tool | Lathe | tool | speed | size | quality |")
    print("|---|---|---|---|---|---|---|")

    for row in comparisons {
        // **A size difference only means something at matched quality.** Two
        // encoders' "q80" are not the same q80, so comparing bytes without
        // checking what was bought with them is how a benchmark misleads — in
        // either direction. Where the two outputs are not within tolerance, the
        // size column says so instead of printing a percentage nobody should
        // act on.
        let matched = row.isQualityMatched
        let size: String
        if let lathe = row.latheBytes, let tool = row.toolBytes, tool > 0 {
            let sizes = "\(format(Double(lathe) / 1024, 0)) vs \(format(Double(tool) / 1024, 0)) KiB"
            size = matched == false
                ? "\(sizes) — *not matched*"
                : "\(sizes) (\(delta(lathe, tool)))"
        } else {
            size = "—"
        }

        let quality: String
        if let lathe = row.latheQuality, let tool = row.toolQuality, let metric = row.qualityMetric {
            let marker = matched == true ? "" : " ⚠︎"
            quality = "\(format(lathe, 2)) vs \(format(tool, 2)) \(metric)\(marker)"
        } else {
            quality = "—"
        }

        print("| \(row.task) | `\(row.tool)` | \(format(row.latheSeconds, 3)) s | "
            + "\(format(row.toolSeconds, 3)) s | \(speedup(lathe: row.latheSeconds, tool: row.toolSeconds)) | "
            + "\(size) | \(quality) |")
    }

    print("""

    ⚠︎ marks a row where the two sides did **not** land at the same quality, so
    the byte counts are not comparable and no percentage is claimed for them. Two
    encoders' "q80" are not the same q80; a size column that ignores that
    misleads in whichever direction the settings happened to fall.

    """)
    print("### What each row is showing\n")
    for row in comparisons {
        print("- **\(row.task)** — \(row.note)")
    }

    if !skipped.isEmpty {
        print("\n### Not run\n")
        for entry in skipped { print("- \(entry)") }
    }

    print("\n### Versions\n")
    print("- Lathe \(LatheVersion.engine)")
    for (name, arguments) in [
        ("ffmpeg", ["-version"]), ("cwebp", ["-version"]), ("cjpeg", ["-version"]),
        ("avifenc", ["--version"]), ("exiftool", ["-ver"]), ("lame", ["--version"]),
    ] where toolExists(name) {
        print("- \(name) \(toolVersion(name, arguments))")
    }
    let machine = (try? shell(["sysctl", "-n", "machdep.cpu.brand_string"]).output) ?? ""
    print("- \(machine.trimmingCharacters(in: .whitespacesAndNewlines)), "
        + "\(ProcessInfo.processInfo.activeProcessorCount) cores, "
        + "macOS \(ProcessInfo.processInfo.operatingSystemVersionString)")

    print("""

    ### The row that cannot be measured here

    Every tool above is a process. Lathe is a library, so it also runs where a
    process cannot be launched at all — inside an iOS app, inside an App Store
    build, inside a daemon that is not allowed to fork. That is not a faster
    version of what these tools do; it is the case they cannot do, and no
    benchmark on a Mac can show it.
    """)
}

await main()
